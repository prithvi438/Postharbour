import { defineConfig } from 'vitest/config';
import react from '@vitejs/plugin-react';

/** Build an offline fallback using only public assets. Authenticated API responses
 * and dashboard HTML are never put in Cache Storage by this service worker. */
export default defineConfig({
  plugins: [
    react(),
    {
      name: 'postharbor-pwa',
      generateBundle(_, bundle) {
        const assets = Object.keys(bundle)
          .filter((name) => /\.(js|css)$/.test(name))
          .map((name) => `/${name}`);
        const version = assets.join('|');
        this.emitFile({
          type: 'asset',
          fileName: 'sw.js',
          source: `
// Generated by vite.config.ts. Never cache /api or personal mailbox data.
const CACHE = 'postharbor-' + ${JSON.stringify(version)};
const ASSETS = ${JSON.stringify([...assets, '/offline.html', '/icons/icon-192.png', '/icons/icon-512.png'])};
self.addEventListener('install', event => {
  event.waitUntil(caches.open(CACHE).then(cache => cache.addAll(ASSETS)));
});
self.addEventListener('activate', event => {
  event.waitUntil(caches.keys().then(keys => Promise.all(keys.filter(key => key.startsWith('postharbor-') && key !== CACHE).map(key => caches.delete(key)))).then(() => self.clients.claim()));
});
self.addEventListener('fetch', event => {
  const url = new URL(event.request.url);
  if (event.request.method !== 'GET' || url.origin !== self.location.origin || url.pathname.startsWith('/api/') || url.pathname === '/healthz') return;
  if (event.request.mode === 'navigate') {
    event.respondWith(fetch(event.request).catch(() => caches.match('/offline.html')));
  } else if (ASSETS.includes(url.pathname)) {
    event.respondWith(caches.match(event.request).then(cached => cached || fetch(event.request)));
  }
});
`,
        });
      },
    },
  ],
  server: { proxy: { '/api': 'http://127.0.0.1:8080', '/healthz': 'http://127.0.0.1:8080' } },
  test: { environment: 'jsdom', setupFiles: './src/test-setup.ts' },
});
